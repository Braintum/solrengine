<?php
/**
 * An autocomplete request.
 *
 * @package SolrEngine
 */

namespace SolrEngine\Contracts;

/**
 * What a visitor has typed so far.
 *
 * Separate from SearchQuery because the two want different things. A search
 * wants recall and ranking over the whole corpus; an autocomplete wants a
 * handful of titles that start with what is on screen, as fast as possible,
 * and will be thrown away the moment the next key is pressed.
 *
 * Immutable.
 *
 * @since 0.5.0 Unstable until 1.0.
 */
final class SuggestQuery {

	/**
	 * Shortest prefix worth querying for.
	 *
	 * One character matches most of the index and tells the visitor nothing,
	 * while costing a request per keystroke.
	 *
	 * @var int
	 */
	public const MIN_LENGTH = 2;

	/**
	 * What the visitor has typed.
	 *
	 * @var string
	 */
	private $prefix;

	/**
	 * Site to restrict to.
	 *
	 * @var int
	 */
	private $site_id;

	/**
	 * How many suggestions to return.
	 *
	 * @var int
	 */
	private $limit;

	/**
	 * Post types to restrict to.
	 *
	 * @var string[]
	 */
	private $post_types = array();

	/**
	 * Constructor.
	 *
	 * @param string $prefix  What the visitor has typed.
	 * @param int    $site_id Site to restrict to.
	 * @param int    $limit   How many suggestions to return.
	 */
	public function __construct( string $prefix, int $site_id, int $limit = 8 ) {
		$this->prefix  = $prefix;
		$this->site_id = $site_id;
		// Capped low on purpose. A suggestion list longer than a screenful is
		// not a list anybody reads, and every extra row costs latency on the
		// one request type where latency is the whole product.
		$this->limit = max( 1, min( 20, $limit ) );
	}

	/**
	 * What the visitor has typed.
	 *
	 * @since 0.5.0
	 *
	 * @return string
	 */
	public function prefix(): string {
		return $this->prefix;
	}

	/**
	 * Site to restrict to.
	 *
	 * @since 0.5.0
	 *
	 * @return int
	 */
	public function site_id(): int {
		return $this->site_id;
	}

	/**
	 * How many suggestions to return.
	 *
	 * @since 0.5.0
	 *
	 * @return int
	 */
	public function limit(): int {
		return $this->limit;
	}

	/**
	 * Post types to restrict to.
	 *
	 * @since 0.5.0
	 *
	 * @return string[]
	 */
	public function post_types(): array {
		return $this->post_types;
	}

	/**
	 * Whether the prefix is long enough to be worth a request.
	 *
	 * @since 0.5.0
	 *
	 * @return bool
	 */
	public function is_long_enough(): bool {
		return mb_strlen( trim( $this->prefix ) ) >= self::MIN_LENGTH;
	}

	/**
	 * A copy restricted to given post types.
	 *
	 * @since 0.5.0
	 *
	 * @param string[] $post_types Post types.
	 * @return self
	 */
	public function with_post_types( array $post_types ): self {
		$clone             = clone $this;
		$clone->post_types = array_values( array_unique( array_map( 'strval', $post_types ) ) );

		return $clone;
	}

	/**
	 * A stable key identifying this request, for caching.
	 *
	 * The prefix is lowercased and whitespace-collapsed first, so "Mac" and
	 * "mac " share one cache entry. Autocomplete is the one request type where
	 * cache hit rate matters most: a visitor typing eight characters generates
	 * several requests, and the ones before them were probably generated by
	 * somebody else a moment ago.
	 *
	 * @since 0.5.0
	 *
	 * @return string
	 */
	public function cache_key(): string {
		$normalised = mb_strtolower( (string) preg_replace( '/\s+/u', ' ', trim( $this->prefix ) ) );

		return md5(
			(string) wp_json_encode(
				array( $normalised, $this->site_id, $this->limit, $this->post_types )
			)
		);
	}
}
